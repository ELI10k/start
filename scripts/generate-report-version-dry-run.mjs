// Prepares the dry-run for 202608120002_coach_report_versions.sql.
//
// Two outputs, both under backups/coach-report-versions/:
//
//   02-safety-scan.json  what the migration says it does, read off the SQL with
//                        comments stripped - the added columns, and proof that no
//                        statement drops, renames, deletes, truncates or writes a
//                        row.
//   02-dry-run.sql       the migration body verbatim, wrapped in a transaction
//                        that always ends in an exception. It cannot commit; the
//                        exception message is how the post-apply shape of the
//                        table gets out of the aborted transaction.
//
//   node scripts/generate-report-version-dry-run.mjs

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationName = "202608120002_coach_report_versions.sql";
const migrationPath = join(root, "supabase/migrations", migrationName);
const outDir = join(root, "backups/coach-report-versions");

const EXPECTED_COLUMNS = ["edited_went_well", "edited_needs_work", "edited_actions", "approved_at", "approved_by"];

const source = await readFile(migrationPath, "utf8");

// Comments are documentation, not statements. The rollback recipe in this
// migration's header contains the word "drop" five times, and scanning it would
// only produce noise.
const code = source.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/--[^\n]*/g, " ");

const forbidden = [
  ["drops a table", /\bdrop\s+table\b/i],
  ["drops a column", /\bdrop\s+column\b/i],
  ["drops a policy", /\bdrop\s+policy\b/i],
  ["drops a function", /\bdrop\s+function\b/i],
  ["drops an index", /\bdrop\s+index\b/i],
  ["renames something", /\brename\b/i],
  ["deletes rows", /\bdelete\s+from\b/i],
  ["truncates", /\btruncate\b/i],
  ["updates rows", /\bupdate\s+(?:only\s+)?[\w."]+\s+set\b/i],
  ["inserts rows", /\binsert\s+into\b/i],
  ["alters an existing column", /\balter\s+column\b/i],
  ["adds a not-null constraint", /\bset\s+not\s+null\b/i],
  ["changes RLS", /\b(?:enable|disable|force)\s+row\s+level\s+security\b/i],
  ["changes grants", /\b(?:grant|revoke)\b/i],
];

const violations = forbidden.filter(([, pattern]) => pattern.test(code)).map(([label]) => label);

// The one drop in the body is the guard in front of `create trigger`, which is
// how the migration stays re-runnable. It names the trigger this same file
// creates, and that trigger does not exist yet.
const drops = [...code.matchAll(/\bdrop\s+trigger\s+if\s+exists\s+(\w+)\s+on\s+([\w.]+)/gi)]
  .map((match) => ({ trigger: match[1], table: match[2] }));
const strayDrops = [...code.matchAll(/\bdrop\b/gi)].length - drops.length;
if (strayDrops > 0) violations.push(`${strayDrops} drop statement(s) that are not the trigger guard`);
for (const drop of drops) {
  const created = new RegExp(`create\\s+trigger\\s+${drop.trigger}\\b`, "i").test(code);
  if (!created) violations.push(`drops trigger ${drop.trigger} without recreating it`);
}

const addedColumns = [...code.matchAll(/add\s+column\s+if\s+not\s+exists\s+(\w+)\s+([a-z\[\]]+)/gi)]
  .map((match) => ({ name: match[1], type: match[2] }));
const addedNames = addedColumns.map((column) => column.name);
const unexpected = addedNames.filter((name) => !EXPECTED_COLUMNS.includes(name));
const missing = EXPECTED_COLUMNS.filter((name) => !addedNames.includes(name));
if (unexpected.length) violations.push(`adds unexpected column(s): ${unexpected.join(", ")}`);
if (missing.length) violations.push(`does not add: ${missing.join(", ")}`);

// Everything the migration creates that is not a column, so the report can name
// it rather than let it arrive unannounced.
const otherObjects = [
  ...[...code.matchAll(/create\s+(?:or\s+replace\s+)?function\s+([\w.]+)/gi)].map((m) => `function ${m[1]}`),
  ...[...code.matchAll(/create\s+trigger\s+(\w+)/gi)].map((m) => `trigger ${m[1]}`),
];

const scan = {
  migration: migrationName,
  bytes: source.length,
  expectedColumns: EXPECTED_COLUMNS,
  addedColumns,
  otherObjectsCreated: otherObjects,
  dropTriggerGuards: drops,
  forbiddenPatternsMatched: violations,
  verdict: violations.length ? "BLOCKED" : "SAFE: additive only, writes no rows",
};

// The body, verbatim. Only the migration's own transaction control comes off -
// the dry-run supplies its own, and a nested begin would be ignored anyway.
const body = source.replace(/^\s*begin;\s*\n/i, "").replace(/\n\s*commit;\s*\n?\s*$/i, "\n");
if (/^\s*(begin|commit|rollback)\s*;/im.test(body)) throw new Error("stray transaction control left in the migration body");

const dryRun = `-- DRY RUN of supabase/migrations/${migrationName}
-- Generated by scripts/generate-report-version-dry-run.mjs. Do not edit by hand.
--
-- The body below is the migration verbatim, minus its own begin;/commit;. It runs
-- inside a transaction that always ends by raising, so it can only ever roll
-- back - the rollback; at the end is a second lock on the same door. The raise is
-- also the only way to read the post-apply state, since an aborted transaction
-- returns no rows.

begin;

${body}
do $verify$
declare cols text; ncols int; trig text; fn text; n bigint;
begin
  select count(*), string_agg(column_name || ' ' || data_type || ' null=' || is_nullable, ' | ' order by ordinal_position)
    into ncols, cols
    from information_schema.columns where table_schema = 'public' and table_name = 'weekly_summaries';
  select coalesce(string_agg(tgname, ','), '(none)') into trig
    from pg_trigger where tgrelid = 'public.weekly_summaries'::regclass and not tgisinternal;
  select coalesce(string_agg(p.proname, ','), '(none)') into fn
    from pg_proc p join pg_namespace ns on ns.oid = p.pronamespace
    where ns.nspname = 'public' and p.proname = 'freeze_approved_weekly_summary';
  select count(*) into n from public.weekly_summaries;
  raise exception E'DRYRUN-RESULT column_count=% row_count=% triggers=% function=% columns=%', ncols, n, trig, fn, cols;
end
$verify$;

rollback;
`;

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, "02-safety-scan.json"), `${JSON.stringify(scan, null, 2)}\n`);
await writeFile(join(outDir, "02-dry-run.sql"), dryRun);

console.log(JSON.stringify(scan, null, 2));
console.log(`\nwrote ${join(outDir, "02-safety-scan.json")}`);
console.log(`wrote ${join(outDir, "02-dry-run.sql")}`);
if (violations.length) process.exitCode = 1;
