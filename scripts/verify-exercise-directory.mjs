import assert from "node:assert/strict";
import {config} from "dotenv";
import {createClient} from "@supabase/supabase-js";
import {chromium} from "@playwright/test";
config({path:new URL("../.env.e2e",import.meta.url).pathname,quiet:true});
config({path:new URL("../.env.local",import.meta.url).pathname,quiet:true});
const base=process.argv[2]??"http://127.0.0.1:3027";
const url=process.env.NEXT_PUBLIC_SUPABASE_URL;
const client=createClient(url,process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const {data,error}=await client.auth.signInWithPassword({email:process.env.E2E_COACH_EMAIL,password:process.env.E2E_COACH_PASSWORD});
if(error)throw new Error(`Test coach sign-in failed: ${error.code}`);
const key=`sb-${new URL(url).hostname.split(".")[0]}-auth-token`;
const encoded=`base64-${Buffer.from(JSON.stringify(data.session)).toString("base64url")}`;
const cookie={domain:new URL(base).hostname,path:"/",secure:base.startsWith("https"),sameSite:"Lax"};
const cookies=[];
for(let n=0;n*3180<encoded.length;n++)cookies.push({...cookie,name:encoded.length<=3180?key:`${key}.${n}`,value:encoded.slice(n*3180,(n+1)*3180)});
cookies.push({...cookie,name:"start-device-id",value:"exercise-directory-verification"});
const browser=await chromium.launch({headless:true});
try {
 const context=await browser.newContext({viewport:{width:1280,height:1000},locale:"he-IL"});
 await context.addCookies(cookies);
 const page=await context.newPage();
 await page.goto(`${base}/coach/workouts/exercises`,{waitUntil:"domcontentloaded"});
 await page.getByRole("button",{name:/רגליים.*תרגילים/}).waitFor();
 assert.equal(await page.locator('svg[role="img"]').count(),7);
 assert.equal(await page.locator("article").count(),0);
 await page.getByRole("button",{name:/רגליים.*תרגילים/}).click();
 await page.getByLabel("חיפוש תרגיל",{exact:true}).fill("הרחקת ירך");
 assert.ok(await page.locator("article").count()>0);
 assert.ok((await page.locator("article").allTextContents()).every(t=>t.includes("דגש: ישבן צידי")));
 await page.getByRole("button",{name:"כל קבוצות השרירים"}).click();
 await page.getByRole("button",{name:/כתפיים.*תרגילים/}).click();
 await page.getByLabel("דגש שרירי",{exact:true}).selectOption("כתף אמצעית");
 assert.ok(await page.locator("article").count()>0);
 assert.ok((await page.locator("article").allTextContents()).every(t=>t.includes("דגש: כתף אמצעית")));
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),"mobile overflow");
 await page.getByRole("button",{name:"כל קבוצות השרירים"}).click();
 await page.getByLabel("חיפוש תרגיל",{exact:true}).fill("אופניים");
 await page.getByRole("heading",{name:"אופניים — בטן",exact:true}).waitFor();
 await page.getByRole("link",{name:"פתיחת פרטי אופניים — בטן",exact:true}).click();
 await page.getByRole("heading",{name:"אופניים — בטן",exact:true}).waitFor();
 await page.goto(`${base}/coach/workouts/exercises`,{waitUntil:"networkidle"});
 await page.getByLabel("חיפוש תרגיל",{exact:true}).fill("לשון צונחת");
 await page.getByRole("heading",{name:"כפיפות בטן (קראנץ׳) — בטן",exact:true}).waitFor();
 await page.getByLabel("חיפוש תרגיל",{exact:true}).fill("בטן");
 await page.getByRole("combobox",{name:"ציוד נדרש",exact:true}).selectOption("home");
 assert.ok(await page.locator("article").count()>0);
 assert.ok((await page.locator('article [aria-label="ציוד נדרש"]').allTextContents()).every(t=>!t.includes("מכונות")&&!t.includes("פולי")));
 console.log(JSON.stringify({base,folders:7,initialExercisesHidden:true,glutes:true,shoulderFocus:true,mobile:true,detail:true,legacyAlias:true,homeEquipment:true}));
} finally {await browser.close();await client.auth.signOut({scope:"local"});}
